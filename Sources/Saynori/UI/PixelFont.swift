import Foundation

/// A hand-drawn proportional pixel font: 5 px wide, cap height 7, two descender rows.
/// Each glyph is a key line followed by up to nine rows of `.`/`#`; blank columns on either
/// side are trimmed, so narrow letters (i, l, 1, punctuation) sit tight like a real pixel face.
enum PixelFont {
    static let capHeight = 7
    static let boxHeight = 9
    static let spaceWidth = 3
    static let tracking = 1

    struct Glyph {
        let width: Int
        /// Lit cells as (column, row), row 0 = top of the cap height.
        let cells: [(Int, Int)]
    }

    static let glyphs: [Character: Glyph] = parse(source)

    private static let aliases: [Character: Character] = [
        "’": "'", "‘": "'", "“": "\"", "”": "\"", "—": "-", "–": "-", "•": "*", "×": "x",
    ]

    static func glyph(_ c: Character) -> Glyph? {
        glyphs[c] ?? aliases[c].flatMap { glyphs[$0] }
    }

    /// Whether every character can be drawn with this font.
    static func supports(_ text: String) -> Bool {
        text.allSatisfy { $0 == " " || glyph($0) != nil }
    }

    static func width(of text: String) -> Int {
        var w = 0
        for (i, c) in text.enumerated() {
            if i > 0 { w += tracking }
            w += c == " " ? spaceWidth : (glyph(c)?.width ?? spaceWidth)
        }
        return w
    }

    /// Longest run of whole words that fits `maxWidth` cells, with "…" when it's cut short.
    static func fit(_ text: String, maxWidth: Int) -> String {
        let words = text.replacingOccurrences(of: "\n", with: " ").split(separator: " ").map(String.init)
        var out = ""
        for w in words {
            let next = out.isEmpty ? w : out + " " + w
            if width(of: next + "…") > maxWidth {
                if out.isEmpty {
                    var cut = ""
                    for ch in w where width(of: cut + String(ch) + "…") <= maxWidth { cut.append(ch) }
                    return cut + "…"
                }
                return out + "…"
            }
            out = next
        }
        return out
    }

    private static func parse(_ src: String) -> [Character: Glyph] {
        var out = [Character: Glyph]()
        var key: Character?
        var rows = [String]()
        func flush() {
            guard let key else { return }
            var cells = [(Int, Int)]()
            for (r, row) in rows.enumerated() {
                for (c, ch) in row.enumerated() where ch == "#" { cells.append((c, r)) }
            }
            let minC = cells.map(\.0).min() ?? 0, maxC = cells.map(\.0).max() ?? 0
            out[key] = Glyph(width: maxC - minC + 1, cells: cells.map { ($0.0 - minC, $0.1) })
        }
        for line in src.split(separator: "\n", omittingEmptySubsequences: true) {
            if line.count == 1 {
                flush()
                key = line.first
                rows = []
            } else {
                rows.append(String(line))
            }
        }
        flush()
        return out
    }

